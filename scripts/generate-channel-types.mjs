import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../vendor/new-api/v1.0.0-rc.45/channel-constants.excerpt.ts", import.meta.url), "utf8");
const typesBlock = source.slice(source.indexOf("export const CHANNEL_TYPES = {"), source.indexOf("} as const"));
const types = {};
for (const match of typesBlock.matchAll(/^\s*(\d+):\s*'([^']*)',?/gm)) {
  types[Number(match[1])] = match[2];
}
const orderBlock = source.slice(source.indexOf("CHANNEL_TYPE_DISPLAY_ORDER"), source.indexOf("export const CHANNEL_TYPE_OPTIONS"));
const order = [...orderBlock.matchAll(/\d+/g)].map(Number);
const promptBlock = source.slice(source.indexOf("export const TYPE_TO_KEY_PROMPT"), source.indexOf("export const CHANNEL_TYPE_WARNINGS"));
const prompts = {};
for (const match of promptBlock.matchAll(/^\s*(\d+):\s*'([^']*)',?/gm)) {
  prompts[Number(match[1])] = match[2];
}

const colors = ["#34C759", "#FF2D55", "#A2845E", "#FF3B30", "#5AC8FA", "#FF9500", "#007AFF", "#AF52DE"];
const seen = new Set();
const options = [];
for (const id of order) {
  if (types[id] && id !== 0 && !seen.has(id)) {
    options.push({ id, name: types[id] });
    seen.add(id);
  }
}
for (const [key, name] of Object.entries(types)) {
  const id = Number(key);
  if (id !== 0 && !seen.has(id)) options.push({ id, name });
}

const lines = options.map((item, index) => {
  const hint = prompts[item.id] ? JSON.stringify(prompts[item.id]) : "\"\"";
  return `  { id: ${item.id}, name: ${JSON.stringify(item.name)}, color: "${colors[index % colors.length]}", keyHint: ${hint} },`;
});

const out = `/* Generated by scripts/generate-channel-types.mjs from vendor/new-api/v1.0.0-rc.45/channel-constants.excerpt.ts
 * QuantumNous/new-api v1.0.0-rc.45. Do not edit by hand.
 */
export const NEW_API_RELEASE = "v1.0.0-rc.45";

export type ChannelTypeOption = { id: number; name: string; color: string; keyHint: string };

export const CHANNEL_TYPE_OPTIONS: ChannelTypeOption[] = [
${lines.join("\n")}
];

export function channelTypeName(id: number): string {
  return CHANNEL_TYPE_OPTIONS.find((item) => item.id === id)?.name ?? \`类型 \${id}\`;
}

export function channelTypeOption(id: number): ChannelTypeOption {
  return CHANNEL_TYPE_OPTIONS.find((item) => item.id === id) ?? { id, name: channelTypeName(id), color: "#71717A", keyHint: "" };
}
`;
writeFileSync(new URL("../lib/channel-types.generated.ts", import.meta.url), out);
console.log("types", options.length);
